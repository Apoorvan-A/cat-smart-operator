import type { Provenance, Severity } from "@/api/types";

/** Minimal classnames helper — avoids pulling in a dependency for one job. */
export function cx(...parts: Array<string | false | null | undefined>): string {
  return parts.filter(Boolean).join(" ");
}

export function timeOf(isoStr: string): string {
  const d = new Date(isoStr);
  if (Number.isNaN(d.getTime())) return "--:--";
  // Render in UTC — the contract stores all timestamps as ISO-8601 UTC and the
  // demo script refers to shift times (14:30 → 14:47) as written, so we don't
  // shift them into the viewer's local timezone.
  return d.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit", hour12: false, timeZone: "UTC" });
}

export function relAge(seconds: number): string {
  if (seconds < 60) return `${Math.round(seconds)}s ago`;
  const m = Math.floor(seconds / 60);
  const s = Math.round(seconds % 60);
  return `${m}m ${s.toString().padStart(2, "0")}s ago`;
}

export function pct(n: number): string {
  return `${Math.round(n * 100)}%`;
}

