export function healthColor(state: string): string {
  switch (state) {
    case "NORMAL":
      return "text-ok";
    case "WARNING":
      return "text-sev-warning";
    case "DEGRADED":
      return "text-sev-high";
    case "CRITICAL":
      return "text-sev-critical";
    default:
      return "text-fg-muted";
  }
}
